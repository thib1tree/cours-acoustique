// Writes the colormap LUTs used by the static design mockups (docs/design/).
import { writeFileSync } from 'node:fs';
import { energyMap, pressureMap } from '../src/lib/color/palette';
import { toRgba8 } from '../src/lib/color/colormaps';

const luts: Record<string, number[]> = {};
for (const t of ['light', 'dark'] as const) {
  luts[`pressure-${t}`] = Array.from(toRgba8(pressureMap(t, 257)));
  luts[`energy-${t}`] = Array.from(toRgba8(energyMap(t, 256)));
}
writeFileSync(
  new URL('../docs/design/shared/luts.js', import.meta.url),
  `// Generated by scripts/gen-design-luts.ts from src/lib/color/palette.ts.\nwindow.LUTS = ${JSON.stringify(luts)};\n`,
);
